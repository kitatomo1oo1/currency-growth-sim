interface EventSpec {
  id: string;
  category: EventCategory;
  label: string;
  weight?: number;
  severity?: [number, number];
  cooldown?: number;
  repeatable?: boolean;
  prereq?: EventPrerequisite[];
  forbidden?: EventPrerequisite[];
  conflictTags?: string[];
  topics?: string[];
  text: string;
  effects: (s: number) => EffectInstruction[];
  /** 数年後に効いてくる遅延効果の種。大きな出来事に「その後の展開」を持たせるために使う(§34)。 */
  delayed?: (s: number, currentYear: number) => Array<Omit<DelayedEffectRecord, "id" | "createdYear">>;
}

function defineEvent(spec: EventSpec): EventDefinition {
  return {
    id: spec.id,
    category: spec.category,
    label: spec.label,
    prerequisites: spec.prereq ?? [],
    forbiddenIf: spec.forbidden ?? [],
    baseWeight: spec.weight ?? 1,
    severityRange: { min: spec.severity?.[0] ?? 0.3, max: spec.severity?.[1] ?? 0.8 },
    conflictTags: spec.conflictTags ?? [],
    cooldownYears: spec.cooldown ?? 3,
    repeatable: spec.repeatable ?? true,
    learningTopics: spec.topics ?? [],
    textTemplate: spec.text,
    buildImmediateEffects: spec.effects,
    buildDelayedEffects: spec.delayed,
  };
}

